create or replace function public.place_order(p_customer jsonb, p_items jsonb, p_promo_code text default null)
returns jsonb language plpgsql security definer set search_path = public, extensions as $$
declare
  customer_name text;
  customer_email text;
  customer_phone text;
  customer_address text;
  customer_postal text;
  customer_city text;
  customer_country text;
  customer_id uuid;
  order_id uuid;
  order_no bigint;
  line record;
  product_row record;
  subtotal numeric(10,2) := 0;
  discount numeric(10,2) := 0;
  total numeric(10,2) := 0;
  promo_row public.promotions%rowtype;
  promo text := nullif(upper(trim(coalesce(p_promo_code, ''))), '');
begin
  customer_name := trim(coalesce(p_customer->>'full_name', ''));
  customer_email := lower(trim(coalesce(p_customer->>'email', '')));
  customer_phone := trim(coalesce(p_customer->>'phone', ''));
  customer_address := trim(coalesce(p_customer->>'address', ''));
  customer_postal := trim(coalesce(p_customer->>'postal_code', ''));
  customer_city := trim(coalesce(p_customer->>'city', ''));
  customer_country := coalesce(nullif(trim(p_customer->>'country'), ''), 'France');

  if length(customer_name) < 2 or length(customer_name) > 120 then raise exception 'invalid_customer_name'; end if;
  if customer_email !~* '^[A-Z0-9._%+-]+@[A-Z0-9.-]+\.[A-Z]{2,}$' then raise exception 'invalid_customer_email'; end if;
  if length(customer_phone) < 7 or length(customer_phone) > 30 then raise exception 'invalid_customer_phone'; end if;
  if customer_address = '' or customer_postal = '' or customer_city = '' then raise exception 'invalid_delivery_address'; end if;
  if jsonb_typeof(p_items) <> 'array' or jsonb_array_length(p_items) < 1 or jsonb_array_length(p_items) > 30 then raise exception 'invalid_order_lines'; end if;

  for line in select variant_id, quantity from jsonb_to_recordset(p_items) as item(variant_id uuid, quantity integer) order by variant_id loop
    if line.quantity is null or line.quantity < 1 or line.quantity > 20 then raise exception 'invalid_quantity'; end if;
    select p.id as product_id, p.name as product_name, p.price as base_price, p.image_url, pv.id as variant_id, pv.name as variant_name, pv.value as variant_value, pv.price_delta, pv.stock
      into product_row
      from public.product_variants pv join public.products p on p.id = pv.product_id
      where pv.id = line.variant_id and p.active = true
      for update of p, pv;
    if not found then raise exception 'product_unavailable'; end if;
    if product_row.stock < line.quantity then raise exception 'insufficient_stock:%', product_row.product_name; end if;
    subtotal := subtotal + (product_row.base_price + product_row.price_delta) * line.quantity;
  end loop;

  if promo is not null then
    select * into promo_row from public.promotions
      where upper(code) = promo and active = true
        and (starts_at is null or starts_at <= now())
        and (ends_at is null or ends_at >= now())
        and (usage_limit is null or used_count < usage_limit)
      for update;
    if not found then raise exception 'invalid_promotion'; end if;
    if promo_row.discount_type = 'percent' then discount := round(subtotal * promo_row.discount_value / 100, 2);
    else discount := promo_row.discount_value;
    end if;
    discount := least(subtotal, discount);
  end if;
  total := greatest(0, subtotal - discount);

  insert into public.customers (full_name, email, phone, address, postal_code, city, country)
    values (customer_name, customer_email, customer_phone, customer_address, customer_postal, customer_city, customer_country)
    on conflict (email) do update set full_name = excluded.full_name, phone = excluded.phone, address = excluded.address,
      postal_code = excluded.postal_code, city = excluded.city, country = excluded.country, updated_at = now()
    returning id into customer_id;

  insert into public.orders (customer_id, subtotal, discount_amount, total, promo_code)
    values (customer_id, subtotal, discount, total, promo) returning id, order_number into order_id, order_no;

  for line in select variant_id, quantity from jsonb_to_recordset(p_items) as item(variant_id uuid, quantity integer) order by variant_id loop
    select p.id as product_id, p.name as product_name, p.price as base_price, p.image_url,
      pv.id as variant_id, pv.name as variant_name, pv.value as variant_value, pv.price_delta, pv.stock
      into product_row
      from public.product_variants pv join public.products p on p.id = pv.product_id
      where pv.id = line.variant_id and p.active = true;
    insert into public.order_items (order_id, product_id, variant_id, product_name, variant_name, variant_value, quantity, unit_price, line_total)
      values (order_id, product_row.product_id, product_row.variant_id, product_row.product_name, product_row.variant_name, product_row.variant_value,
        line.quantity, product_row.base_price + product_row.price_delta, (product_row.base_price + product_row.price_delta) * line.quantity);
    update public.product_variants set stock = stock - line.quantity where id = line.variant_id;
  end loop;

  if promo is not null then update public.promotions set used_count = used_count + 1 where id = promo_row.id; end if;
  return jsonb_build_object('id', order_id, 'order_number', order_no, 'customer_id', customer_id, 'subtotal', subtotal, 'discount_amount', discount, 'total', total, 'promo_code', promo);
end;
$$;
revoke all on function public.place_order(jsonb, jsonb, text) from public, anon, authenticated;
grant execute on function public.place_order(jsonb, jsonb, text) to service_role;

