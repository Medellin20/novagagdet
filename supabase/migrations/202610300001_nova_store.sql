create or replace function public.sync_product_stock()
returns trigger language plpgsql security definer set search_path = public as $$
declare target_id uuid;
begin
  if tg_op = 'DELETE' then target_id := old.product_id; else target_id := new.product_id; end if;
  update public.products
  set stock = coalesce((select sum(stock) from public.product_variants where product_id = target_id), 0), updated_at = now()
  where id = target_id;
  if tg_op = 'DELETE' then return old; else return new; end if;
end;
$$;

drop trigger if exists nova_variant_stock_sync on public.product_variants;
create trigger nova_variant_stock_sync after insert or update of stock or delete on public.product_variants
for each row execute function public.sync_product_stock();

