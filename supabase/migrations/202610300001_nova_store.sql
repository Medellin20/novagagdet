create or replace function public.replace_product_variants(p_product_id uuid, p_variants jsonb)
returns void language plpgsql security definer set search_path = public as $$
begin
  if not exists (select 1 from public.products where id = p_product_id) then raise exception 'product_not_found'; end if;
  if jsonb_typeof(p_variants) <> 'array' or jsonb_array_length(p_variants) < 1 or jsonb_array_length(p_variants) > 24 then raise exception 'invalid_variants'; end if;
  delete from public.product_variants where product_id = p_product_id;
  insert into public.product_variants (product_id, name, value, price_delta, stock, sku)
  select p_product_id, variant.name, variant.value, variant.price_delta, variant.stock, nullif(variant.sku, '')
  from jsonb_to_recordset(p_variants) as variant(name text, value text, price_delta numeric, stock integer, sku text);
end;
$$;
revoke all on function public.replace_product_variants(uuid, jsonb) from public, anon, authenticated;
grant execute on function public.replace_product_variants(uuid, jsonb) to service_role;


create or replace function public.update_order_status(p_order_id uuid, p_status text)
returns jsonb language plpgsql security definer set search_path = public as $$
declare
  current_status text;
  line record;
begin
  if p_status not in ('pending', 'confirmed', 'preparing', 'shipped', 'delivered', 'cancelled') then raise exception 'invalid_order_status'; end if;
  select status into current_status from public.orders where id = p_order_id for update;
  if not found then raise exception 'order_not_found'; end if;
  if current_status = p_status then return jsonb_build_object('id', p_order_id, 'status', p_status); end if;

  if not (
    (current_status = 'pending' and p_status in ('confirmed', 'cancelled')) or
    (current_status = 'confirmed' and p_status in ('preparing', 'cancelled')) or
    (current_status = 'preparing' and p_status in ('shipped', 'cancelled')) or
    (current_status = 'shipped' and p_status = 'delivered')
  ) then raise exception 'invalid_order_transition'; end if;

  if p_status = 'cancelled' then
    for line in select variant_id, quantity from public.order_items where order_id = p_order_id and variant_id is not null order by variant_id loop
      update public.product_variants set stock = stock + line.quantity where id = line.variant_id;
    end loop;
  end if;

  update public.orders set status = p_status, updated_at = now() where id = p_order_id;
  return jsonb_build_object('id', p_order_id, 'status', p_status);
end;
$$;
revoke all on function public.update_order_status(uuid, text) from public, anon, authenticated;
grant execute on function public.update_order_status(uuid, text) to service_role;
